// Builds supabase/seed.sql from the demo brand files in /demo.
// Usage: node scripts/generate-seed.mjs > supabase/seed.sql
import { readFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../demo/${f}`, import.meta.url), "utf8"));
const brand = read("brand.json");
const rules = read("rules.json");
const facts = read("facts.json");

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const STANDARD = new Set(["id", "category", "severity", "check", "scope", "rule", "guideline", "good", "bad"]);

const out = [];
out.push("-- Generated by scripts/generate-seed.mjs. Fictional demo brand: Oatvia Foods.");
out.push(
  `insert into public.brands (slug, name, settings) values ('oatvia', ${q(brand.name)}, ${j(brand)})\n` +
    `on conflict (slug) do update set name = excluded.name, settings = excluded.settings;`
);
for (const r of rules) {
  const params = Object.fromEntries(Object.entries(r).filter(([k]) => !STANDARD.has(k)));
  out.push(
    `insert into public.rules (brand_id, id, category, severity, check_type, scope, rule, guideline, good, bad, params)\n` +
      `select b.id, ${q(r.id)}, ${q(r.category)}, ${q(r.severity)}, ${q(r.check)}, ${q(r.scope)}, ${q(r.rule)}, ${q(r.guideline)}, ${q(r.good)}, ${q(r.bad)}, ${j(params)}\n` +
      `from public.brands b where b.slug = 'oatvia'\n` +
      `on conflict (brand_id, id) do update set category = excluded.category, severity = excluded.severity, check_type = excluded.check_type, scope = excluded.scope, rule = excluded.rule, guideline = excluded.guideline, good = excluded.good, bad = excluded.bad, params = excluded.params;`
  );
}
for (const f of facts) {
  out.push(
    `insert into public.facts (brand_id, id, product, fact, source, valid_until, type)\n` +
      `select b.id, ${q(f.id)}, ${q(f.product)}, ${q(f.fact)}, ${q(f.source)}, ${q(f.valid_until)}, ${q(f.type)}\n` +
      `from public.brands b where b.slug = 'oatvia'\n` +
      `on conflict (brand_id, id) do update set product = excluded.product, fact = excluded.fact, source = excluded.source, valid_until = excluded.valid_until, type = excluded.type;`
  );
}
console.log(out.join("\n\n"));
